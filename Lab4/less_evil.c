void encryption(node_t* head, int len) {
    int i;
    int temp;
    int initval;
    node_t* cur = head->next;
    /*
    Here is where temp gets used. As you can see, it is a simple modulus check.
    */
    if(len % 2) { // 2nd call, len % 2 != 0. RAND2
        initval = head->value;
    } else { // 1st call. Grabs RAND. Could be done a lot easier, but no
        initval = head->padding;
    }
    i = 0;
    while(cur != NULL) { // Go over the created list
        if(len % 2) { 
            // 2nd call, we need to grab the already "encrypted" data from the list
            temp = cur->padding;
        } else { // 1st call, grab the original string.
            temp = cur->value;
        }

        initval ^= temp; // XOR
        if(i % 2) {     
            initval = ~(initval); // XNOR
        }

        cur->padding = initval; // Set the padding to the "encrypted" 4 bytes
        i++;
        cur = cur->next;
    }
}

/*
Below is mostly generic linked list functions
*/
node_t *ll() {
    node_t* head = (node_t*)malloc(sizeof(node_t));
    head->padding = RAND; // Put RAND in the padding
    head->value = RAND2; // Set head->value to RAND2 without using value
    head->next = NULL;
    return head;
}

void append(node_t *head, int value) {
    // Allocate new node
    node_t* nn = (node_t *)malloc(sizeof(node_t)); 

    // Setup iterator
    node_t* cur = head;

    while(cur->next != NULL) {
        cur = cur->next;
    }

    // Add the new node to the list.
    nn->value = value;
    nn->next = NULL;
    cur->next = nn;
}

// Only used for the exit
int pop_head(node_t* head) {
    if(head->next == NULL) {
        return -1;
    }
    node_t* temp = head->next;
    head->next = temp->next;

    int value = temp->value;
    free(temp);
    temp = NULL;

    return value;
}

// Only used for the exit
void clean_ll(node_t* head) {
    while(head->next != NULL) {
        pop_head(head);
    }
    free(head);
    head = NULL;
}